-- 1. Включаем расширение для работы с векторами в PostgreSQL
CREATE EXTENSION IF NOT EXISTS vector;

-- 2. Создаем таблицу задач
CREATE TABLE tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_number INT NOT NULL,
    subject_slug VARCHAR(50) NOT NULL,
    question_text TEXT NOT NULL,
    options TEXT,
    correct_answer VARCHAR(100) NOT NULL,
    solution_explanation TEXT,
    image_path VARCHAR(255),
    embedding vector(1536),
    CONSTRAINT fk_tasks_subject FOREIGN KEY (subject_slug) REFERENCES subjects(slug) ON DELETE CASCADE
);

-- 3. Создаем индекс для быстрого поиска по предмету
CREATE INDEX idx_tasks_subject_slug ON tasks(subject_slug);

